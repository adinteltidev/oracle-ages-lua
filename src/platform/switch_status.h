#pragma once
// Small built-in 5x7 font for transient save/load feedback; no font assets needed.
static void switch_draw_status(SDL_Renderer *renderer, int width, int height,
                               const char *text, bool error) {
  static const uint8_t glyphs[26][5] = {
    {0x7e,0x11,0x11,0x11,0x7e}, {0x7f,0x49,0x49,0x49,0x36},
    {0x3e,0x41,0x41,0x41,0x22}, {0x7f,0x41,0x41,0x22,0x1c},
    {0x7f,0x49,0x49,0x49,0x41}, {0x7f,0x09,0x09,0x09,0x01},
    {0x3e,0x41,0x49,0x49,0x7a}, {0x7f,0x08,0x08,0x08,0x7f},
    {0x00,0x41,0x7f,0x41,0x00}, {0x20,0x40,0x41,0x3f,0x01},
    {0x7f,0x08,0x14,0x22,0x41}, {0x7f,0x40,0x40,0x40,0x40},
    {0x7f,0x02,0x0c,0x02,0x7f}, {0x7f,0x04,0x08,0x10,0x7f},
    {0x3e,0x41,0x41,0x41,0x3e}, {0x7f,0x09,0x09,0x09,0x06},
    {0x3e,0x41,0x51,0x21,0x5e}, {0x7f,0x09,0x19,0x29,0x46},
    {0x46,0x49,0x49,0x49,0x31}, {0x01,0x01,0x7f,0x01,0x01},
    {0x3f,0x40,0x40,0x40,0x3f}, {0x1f,0x20,0x40,0x20,0x1f},
    {0x3f,0x40,0x38,0x40,0x3f}, {0x63,0x14,0x08,0x14,0x63},
    {0x07,0x08,0x70,0x08,0x07}, {0x61,0x51,0x49,0x45,0x43}
  };
  size_t length = strlen(text);
  if (length > 48) length = 48;
  int scale = height >= 600 ? 3 : 2;
  if ((int)length * 6 * scale + 24 > width) scale = 1;
  int x = (width - (int)length * 6 * scale) / 2;
  int y = height - 7 * scale - 24;
  SDL_Rect background = {x - 12, y - 10, (int)length * 6 * scale + 24, 7 * scale + 20};
  SDL_SetRenderDrawColor(renderer, 16, 20, 24, 255);
  SDL_RenderFillRect(renderer, &background);
  SDL_SetRenderDrawColor(renderer, error ? 255 : 130, error ? 120 : 255, error ? 100 : 170, 255);
  SDL_Rect dots[48 * 35]; int count = 0;
  for (size_t i = 0; i < length; ++i) {
    unsigned char c = (unsigned char)text[i];
    for (int col = 0; col < 5; ++col) {
      uint8_t bits = c >= 'A' && c <= 'Z' ? glyphs[c - 'A'][col] : c == '.' && col == 2 ? 0x40 : 0;
      for (int row = 0; row < 7; ++row)
        if (bits & (1 << row)) dots[count++] = (SDL_Rect){x + ((int)i * 6 + col) * scale, y + row * scale, scale, scale};
    }
  }
  if (count) SDL_RenderFillRects(renderer, dots, count);
}
